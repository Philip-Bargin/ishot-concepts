// Writes wordpress/seed/prototype-content.json from the React prototype's content, for
// `wp ishot import-prototype` (see wordpress/wp-content/plugins/ishot-booking/src/Content/Importer.php).
//
// Exported: categories, photos (with their alt text, focus point and portfolio order), services and
// the two sample projects. NOT exported, on purpose: journal posts (sample copy), sample bookings,
// contact details and stats (owner-confirmed in docs/content-inventory.md), and testimonials
// (the prototype has none; real ones need the client's consent).
// Everything the importer creates from this file is marked "placeholder" until the owner approves it.
//
// Usage: npm run seed:export
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { categories, services } from "../src/data.js";
import { photos, portfolio } from "../src/assets.js";
import { projects } from "../src/prototype/sampleContent.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const IMAGE_WIDTH = 2400; // largest optimised size; within the plan's 2560px upload cap

const keyOf = new Map(Object.entries(photos).map(([key, photo]) => [photo, key]));
const ref = (photo) => {
  if (!photo) return null;
  const key = keyOf.get(photo);
  if (!key) throw new Error("export-wp-seed: a photo is not registered in src/assets.js");
  return key;
};
const slugify = (s) => s.toLowerCase().replace(/&/g, " ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const alts = new Set();
for (const [key, p] of Object.entries(photos)) {
  if (!p.alt?.trim()) throw new Error(`export-wp-seed: photo ${key} has no alt text`);
  if (alts.has(p.alt)) throw new Error(`export-wp-seed: photo ${key} repeats another photo's alt text`);
  alts.add(p.alt);
}

const seed = {
  _about:
    "GENERATED by scripts/export-wp-seed.mjs from the React prototype. All of it is placeholder content: the importer marks it so, leaves prices and deposits unset and creates drafts.",
  categories: categories.map(({ slug, label, blurb }) => ({ slug, label, blurb })),
  photos: Object.entries(photos).map(([key, p]) => ({ key, image: `${p.file}-${IMAGE_WIDTH}.webp`, alt: p.alt, cat: p.cat, focus: p.focus })),
  portfolio: portfolio.map(ref),
  services: services.map((s) => ({
    key: s.id,
    slug: slugify(s.short),
    title: s.title,
    short: s.short,
    tag: s.tag,
    cat: s.cat,
    icon: s.icon,
    photo: s.photo,
    blurb: s.blurb,
    long: s.long,
  })),
  projects: projects.map((p) => ({
    slug: p.slug,
    title: p.title,
    cat: p.cat,
    location: p.location,
    cover: ref(p.cover),
    lead: p.lead,
    text: p.text,
    // Page order: full-width image, the pair, then the strip; each photo once.
    gallery: [...new Set([p.full, ...p.pair, ...p.strip].map(ref))],
  })),
};

const out = resolve(root, "wordpress/seed/prototype-content.json");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(seed, null, 2) + "\n");
console.log(`export-wp-seed: wrote ${seed.categories.length} categories, ${seed.photos.length} photos, ${seed.services.length} services, ${seed.projects.length} projects to wordpress/seed/prototype-content.json`);
