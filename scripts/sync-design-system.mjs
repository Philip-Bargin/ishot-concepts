// Copies the vendored design system (design-system/) into src/styles/ds/ for the app to import.
// - tokens.css is copied as-is.
// - components/bundle.css has its Google Fonts @import removed: fonts are self-hosted
//   via @fontsource (see src/main.jsx), so no third-party font requests are made.
// Runs automatically before `npm run dev` and `npm run build`. Never edit src/styles/ds/ by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "src/styles/ds");
mkdirSync(outDir, { recursive: true });

const banner = "/* GENERATED by scripts/sync-design-system.mjs from design-system/. Do not edit. */\n";

const tokens = readFileSync(resolve(root, "design-system/tokens.css"), "utf8");
const bundleSrc = readFileSync(resolve(root, "design-system/components/bundle.css"), "utf8");
const bundle = bundleSrc.replace(/^@import url\([^)]*fonts\.googleapis\.com[^)]*\);[ \t]*\r?\n?/m, "");

if (bundle === bundleSrc) {
  console.warn("sync-design-system: no Google Fonts @import found in bundle.css; check the vendored file.");
}

writeFileSync(resolve(outDir, "tokens.css"), banner + tokens);
writeFileSync(resolve(outDir, "bundle.css"), banner + bundle);
console.log("sync-design-system: wrote src/styles/ds/tokens.css and bundle.css");
