// Generates ishot-blocks/src/Icons/lucide-data.php from the Lucide icons the prototype uses.
// Each icon is rendered by the prototype's own wrapper settings (Icon.jsx: size 16, stroke 1.5,
// square caps, aria-hidden, focusable=false), so the PHP markup equals the React output.
//
// Usage: node scripts/export-icons.mjs           write the data file
//        node scripts/export-icons.mjs --check   fail when the committed file is stale
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const target = join(root, "wordpress/wp-content/plugins/ishot-blocks/src/Icons/lucide-data.php");

// kebab-case name => lucide-react export. Prototype imports plus ishot-booking Fields::ICONS.
export const ICONS = {
  "arrow-right": "ArrowRight", briefcase: "Briefcase", "calendar-plus": "CalendarPlus", camera: "Camera",
  "chevron-left": "ChevronLeft", "chevron-right": "ChevronRight", circle: "Circle", "circle-alert": "CircleAlert",
  "circle-check": "CircleCheck", "circle-x": "CircleX", clock: "Clock", heart: "Heart", info: "Info",
  "link-2": "Link2", mail: "Mail", menu: "Menu", pause: "Pause", play: "Play", sparkles: "Sparkles",
  sun: "Sun", video: "Video", x: "X",
  image: "Image", users: "Users", film: "Film", star: "Star",
};

export function generate() {
  const names = Object.keys(ICONS).sort();
  const lines = names.map((name) => {
    const Glyph = lucide[ICONS[name]];
    if (!Glyph) throw new Error(`lucide-react has no ${ICONS[name]}`);
    const svg = renderToStaticMarkup(
      createElement(Glyph, { size: 16, strokeWidth: 1.5, strokeLinecap: "square", "aria-hidden": "true", focusable: "false" }),
    );
    if (svg.includes("'")) throw new Error(`${name}: unexpected quote`);
    return `\t'${name}' => '${svg}',`;
  });
  return `<?php
/**
 * GENERATED by scripts/export-icons.mjs. Do not edit by hand; run \`npm run build:icons\`.
 *
 * Lucide icons (https://lucide.dev, lucide-react ${JSON.parse(readFileSync(join(root, "node_modules/lucide-react/package.json"), "utf8")).version}) used by the prototype and by the
 * iShot Booking service icon list, rendered with the prototype's Icon settings.
 *
 * Lucide is licensed under the ISC licence. Copyright (c) for Lucide Contributors 2022; portions
 * Copyright (c) 2013-2022 Cole Bemis (Feather). Permission to use, copy, modify, and/or distribute
 * this software for any purpose with or without fee is hereby granted, provided that the above
 * copyright notice and this permission notice appear in all copies.
 */

// phpcs:disable WordPress.Arrays.MultipleStatementAlignment -- generated file, one icon per line.

return array(
${lines.join("\n")}
);
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch { /* missing */ }
    if (current !== out) { console.error("lucide-data.php is stale. Run: npm run build:icons"); process.exit(1); }
    console.log("lucide-data.php is current.");
  } else {
    writeFileSync(target, out);
    console.log(`Wrote ${target}`);
  }
}
